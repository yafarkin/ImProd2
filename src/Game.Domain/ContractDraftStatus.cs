namespace Game.Domain;

/// <summary>
/// Статус черновика сделки, который переговорщик передал управляющему (SPEC §3: переговорщик готовит
/// черновики, подаёт заявку только управляющий).
/// </summary>
public enum ContractDraftStatus
{
    /// <summary>Черновик у управляющего и ждёт его решения.</summary>
    AwaitingManager,

    /// <summary>Управляющий подал по черновику заявку на сделку — возможно, поправив условия.</summary>
    Submitted,

    /// <summary>Управляющий вернул черновик переговорщику.</summary>
    Returned,

    /// <summary>Переговорщик сам забрал черновик, пока управляющий его не разобрал.</summary>
    Withdrawn
}
