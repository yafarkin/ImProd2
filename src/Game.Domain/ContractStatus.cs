namespace Game.Domain;

/// <summary>
/// Статус контракта (SPEC §6). Условия контракта неизменяемы после подписания — меняется только
/// статус.
/// </summary>
public enum ContractStatus
{
    /// <summary>Условия обеих сторон совпали, код подтверждения выдан, ждём подтверждения управляющим.</summary>
    PendingConfirmation,

    /// <summary>Контракт подтверждён и действует.</summary>
    Active,

    /// <summary>
    /// Разовый (spot) контракт отработал свою единственную поставку — успешную или сорванную — и
    /// больше ничего не исполняет. В отличие от <see cref="Terminated"/> — это штатное завершение,
    /// без штрафа и репутационного удара за само завершение.
    /// </summary>
    Completed,

    /// <summary>Контракт прекращён целиком (SPEC §6: штраф считает Блок 5.2, репутационный удар — Блок 6.2).</summary>
    Terminated,

    /// <summary>
    /// Оператор отклонил контракт на этапе подтверждения (Блок 9.5, SPEC §9.4) — контракт никогда
    /// не был действующим, поэтому не несёт ни штрафа, ни удара по репутации (в отличие от
    /// <see cref="Terminated"/>, который сканирует <c>ReputationCalculator</c>).
    /// </summary>
    Rejected
}
