namespace Game.Domain;

/// <summary>
/// Конкретная причина, по которой две независимо поданные заявки не сошлись (SPEC §6: «конфликт» +
/// подсказка, что разошлось) — структурированно, а не одной строкой, чтобы экран мог явно
/// подсветить именно разошедшееся поле. Причина называет **поле**, а не значение: контрагент не
/// должен узнать чужие числа из подсказки о расхождении, иначе сверка выродится обратно в
/// копирование готовых условий (<c>docs/TODO.md</c> №16).
/// </summary>
public enum ContractMismatchReason
{
    /// <summary>Стороны (покупатель/продавец) не совпадают между заявками.</summary>
    CounterpartiesDiffer,

    /// <summary>Обе заявки поданы от имени одной и той же команды — нужна заявка от каждой стороны.</summary>
    SubmittedByTheSameTeam,

    /// <summary>Разный материал поставки.</summary>
    MaterialDiffers,

    /// <summary>Разный тип контракта — разовый против регулярного.</summary>
    TypeDiffers,

    /// <summary>Разный объём поставки.</summary>
    VolumeDiffers,

    /// <summary>Разная цена за единицу.</summary>
    UnitPriceDiffers,

    /// <summary>Разная ставка штрафа за срыв поставки.</summary>
    PenaltyRateDiffers,

    /// <summary>
    /// Разные сроки: ход поставки у разового контракта либо длительность у регулярного (включая
    /// расхождение «бессрочный против срочного»).
    /// </summary>
    DeliveryScheduleDiffers
}
