namespace Game.Domain;

/// <summary>
/// Статус поданной, но ещё не сведённой заявки на сделку (SPEC §6, <c>docs/TODO.md</c> №16). Заявка
/// живёт в состоянии сессии до тех пор, пока не сойдётся со встречной, не будет отозвана автором или
/// отклонена контрагентом — сам контракт из неё возникает отдельной сущностью.
/// </summary>
public enum ContractProposalStatus
{
    /// <summary>Заявка подана и ждёт встречной от контрагента.</summary>
    Open,

    /// <summary>Заявка сошлась со встречной — контракт заключён.</summary>
    Matched,

    /// <summary>Автор отозвал свою заявку.</summary>
    Withdrawn,

    /// <summary>Контрагент отказался вести сделку по этой заявке.</summary>
    Rejected
}
