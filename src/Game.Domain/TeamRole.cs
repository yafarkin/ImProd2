namespace Game.Domain;

/// <summary>
/// Роль игрока внутри своей команды (SPEC §3) — только те две роли, что имеют значение для домена
/// сделок; «Оператор», «Ведущий», «Администратор» и «Большой экран» не привязаны к команде и сюда
/// не входят (появятся с полноценной моделью ролей в Блоке 8.1).
/// </summary>
public enum TeamRole
{
    /// <summary>Переговорщик: готовит черновики сделок, подтверждать не может.</summary>
    Negotiator,

    /// <summary>Управляющий: единственный, кто даёт финальное подтверждение сделок (1 на команду).</summary>
    Manager
}
