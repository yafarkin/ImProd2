namespace Game.Domain;

/// <summary>
/// Полная ролевая модель участника сессии (Блок 8.1, SPEC §3). «Большой экран» намеренно не входит:
/// это анонимный read-only режим, для него не нужна ни привязка к команде, ни отдельная
/// идентичность — только у ролей из этого списка есть код входа (<see cref="ParticipantRegistration"/>).
/// </summary>
public enum ParticipantRole
{
    /// <summary>Управляющий: единственный, кто даёт финальное подтверждение сделок (1 на команду).</summary>
    Manager,

    /// <summary>Переговорщик: готовит черновики сделок, подтверждать не может (1-2 на команду).</summary>
    Negotiator,

    /// <summary>Оператор: подтверждает сделки по коду, сверяет с бумажным бланком. Не привязан к команде.</summary>
    Operator,

    /// <summary>Ведущий (фасилитатор): управление игрой, вмешательство в экономику, полный обзор всех команд. Не привязан к команде.</summary>
    Facilitator,

    /// <summary>Администратор: настройка сессии до игры, регистрация команд, загрузка конфига. Не привязан к команде.</summary>
    Administrator,
}
