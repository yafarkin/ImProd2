namespace Game.Config.Session;

/// <summary>
/// Стартовые условия команды (SPEC §5.1): фабрик нет, только деньги — кредит свободной суммы
/// под процент, растущий с размером займа. <see cref="BaseLoanInterestRate"/> и
/// <see cref="LoanInterestRateGrowthPerUnitBorrowed"/> — это общая кривая ставки по долгу команды
/// (SPEC §5.9), применяемая не только к стартовому займу, но и к любому последующему кредиту,
/// включая принудительный (последний дополнительно несёт <see cref="ForcedLoanPenaltyRatePerOccurrence"/>
/// — «ставка принудительного займа заведомо хуже любого добровольного»), и надбавку за репутацию
/// (<see cref="MaxReputationRatePenalty"/>, Блок 6.2). Все числа — заглушки, требуют калибровки.
/// </summary>
public sealed record StartingConditionsConfig
{
    /// <summary>
    /// Больше не потолок какого-то отдельного «стартового» кредита — своих правил у первого займа
    /// команды нет, он ничем не отличается от любого следующего (SPEC §5.1: «свободная сумма»,
    /// решает сама команда). Используется как сумма первого займа ботов/тестовых харнессов
    /// (<c>Game.Bots</c>), которым нужен детерминированный старт для калибровки.
    /// </summary>
    public required decimal MaxStartingLoanAmount { get; init; }

    /// <summary>Базовая процентная ставка по долгу команды (за ход).</summary>
    public required decimal BaseLoanInterestRate { get; init; }

    /// <summary>Прирост ставки за каждую единицу текущего долга сверх базовой (долг растёт в цене с размером).</summary>
    public required decimal LoanInterestRateGrowthPerUnitBorrowed { get; init; }

    /// <summary>
    /// Штрафная надбавка к ставке, добавляемая ко всему долгу команды за каждый случай
    /// принудительного кредита (накопительно — см. <see cref="Game.Domain.Team.PenaltyRateSurcharge"/>).
    /// </summary>
    public required decimal ForcedLoanPenaltyRatePerOccurrence { get; init; }

    /// <summary>
    /// Надбавка к ставке при нулевой публичной репутации команды (SPEC §5.9: «ставка зависит от
    /// закредитованности и репутации»); линейно убывает до 0 при 100% репутации. У команды без
    /// истории поставок репутация по умолчанию 100% — надбавка не действует до первого нарекания.
    /// </summary>
    public required decimal MaxReputationRatePenalty { get; init; }

    /// <summary>
    /// Обязательный платёж по телу долга за ход — доля от текущего <see cref="Game.Domain.Team.Debt"/>
    /// (не от исходной суммы займа: долг общий на команду, без учёта происхождения и срока отдельных
    /// займов). Списывается автоматически каждый тик, отдельно от процентов
    /// (<see cref="BaseLoanInterestRate"/>, проценты тело не уменьшают). Если баланса не хватает —
    /// как и на любой другой расход хода, недостачу покрывает принудительный заём
    /// (<see cref="ForcedLoanPenaltyRatePerOccurrence"/>) — то есть непосильный обязательный платёж
    /// не «прощается», а конвертируется в худшую ставку.
    /// </summary>
    public required decimal MandatoryRepaymentRatePerTurn { get; init; }

    /// <summary>
    /// Потолок суммарного долга команды (<see cref="Game.Domain.Team.Debt"/>), который может
    /// покрыть принудительный заём (запрос пользователя: незачем уводить команду в нереалистичные
    /// суммы долга — по-хорошему такую команду вообще стоило бы выводить из игры, но этого пока нет,
    /// поэтому долг просто перестаёт расти дальше потолка). Добровольный <see
    /// cref="Game.Engine.GameSession.TakeLoan"/> этим не ограничен — решение и риск команды. При
    /// достижении потолка <see cref="Game.Engine.ForcedLoanStep"/> покрывает только оставшийся
    /// запас до потолка (может быть меньше фактической дыры в балансе, а при нулевом запасе — не
    /// выдаёт вообще ничего), баланс так и остаётся отрицательным, непокрытым.
    /// </summary>
    public required decimal MaxTotalDebt { get; init; }

    /// <summary>
    /// Потолок итоговой эффективной ставки за ход (после сложения <see cref="BaseLoanInterestRate"/>,
    /// <see cref="LoanInterestRateGrowthPerUnitBorrowed"/>×долг, штрафов и надбавки за репутацию) —
    /// найдено разбором реального прогона LLM-бота (docs/TODO.md #21,
    /// docs/bot-runs/2026-08-19-stage1-gpt-oss-20b/ANALYSIS.md): <see
    /// cref="LoanInterestRateGrowthPerUnitBorrowed"/> растёт линейно от АБСОЛЮТНОЙ суммы долга в
    /// деньгах, без этого потолка — ничем не ограничена и даёт бессмысленные величины ставки уже на
    /// <see cref="MaxTotalDebt"/> (том самом потолке, который добровольный заём демонстративно не
    /// проверяет — «решение и риск команды», см. его doc-comment), а дальше проценты
    /// (<c>долг × ставка</c>) растут фактически квадратично от долга. Здесь — последний рубеж:
    /// сколько бы команда ни назанимала, ставка (и с ней — потери за один ход) остаётся конечной и
    /// осмысленной величиной, даже если долг уже за пределами разумного.
    /// <para>
    /// Первая калибровка (0.5 = 50%/ход) оказалась недостаточной — следующий же прогон показал, что
    /// даже закэпленные 50% на долге, упёршемся в <see cref="MaxTotalDebt"/>, дают проценты в
    /// миллионы за один ход (docs/bot-runs/2026-08-19-stage1-qwen38-v5-crash/ANALYSIS.md): потолок
    /// сделал формулу конечной, но не щадящей. Значение 0.1 (10%/ход) — выбор пользователя после
    /// этой второй находки, не повторно угаданное в одиночку.
    /// </para>
    /// <para>
    /// Третий раунд (2026-08-20, прогон <c>_2bot_gpt_oss_20b_2stage_v2</c>): 0.1 всё ещё не спасает,
    /// но уже по другой причине — добровольный <see cref="Game.Engine.GameSession.TakeLoan"/>
    /// демонстративно не ограничен по сумме (см. его doc-comment), и бот, взявший привычку брать
    /// заём каждый ход (гасить плату за перегруз склада займом вместо того, чтобы продать излишек),
    /// нарастил долг с нуля до 38 млн за 45 ходов — далеко за пределами <see cref="MaxTotalDebt"/>
    /// (10 млн), на который была рассчитана предыдущая калибровка. Понижено до 0.03 (3%/ход) —
    /// прямой запрос пользователя («снизь плату за займ»); заодно <see
    /// cref="LoanInterestRateGrowthPerUnitBorrowed"/> в <c>gameconfig.pilot.json</c>/
    /// <c>sessions/pilot.json</c> выровнен с уже более пологим значением, которое
    /// <c>sessions/training.json</c>/<c>debug.json</c> использовали и раньше (1e-7 вместо 3e-6) —
    /// при старом росте ставка упиралась в потолок уже на ~32 тыс. долга (с потолком 0.1) или ~8 тыс.
    /// (с новым 0.03), то есть «росла» только на бумаге — практически любой заметный заём сразу же
    /// платил по максимальной ставке. Сейчас потолок достигается около 250 тыс. долга — ставка
    /// действительно растёт постепенно на разумном диапазоне сумм, а не скачком. Сам по себе этот
    /// фикс не устраняет привычку модели занимать вместо того, чтобы продавать — только смягчает
    /// последствия; поведенческая часть закрывается подсказкой в <see cref="Game.Bots.Llm.SystemPromptBuilder"/>
    /// и явной секцией текущей стоимости долга в <see cref="Game.Bots.Llm.BotDerivedMetricsBuilder"/>.
    /// **Живым прогоном ещё не проверено.**
    /// </para>
    /// </summary>
    public required decimal MaxLoanInterestRate { get; init; }
}
