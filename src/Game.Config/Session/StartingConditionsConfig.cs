namespace Game.Config.Session;

/// <summary>
/// Стартовые условия команды (SPEC §5.1): фабрик нет, баланс — 0. Никакого банковского займа как
/// класса механики больше нет (пересмотрено, docs/TODO.md #23) — баланс может свободно уходить в
/// минус без процента и без потолка, темп трат ограничивают другие, уже существующие рычаги
/// (<c>MaxCommitmentPerTurn</c> у R&amp;D и у командного исследования поколения, реальная стоимость
/// найма/производства).
/// </summary>
public sealed record StartingConditionsConfig
{
    /// <summary>
    /// Потолок бюджета, который бот/тестовый харнесс (<c>Game.Bots</c>) готов немедленно потратить на
    /// первую разблокированную постройку сектора, не дожидаясь накопления собственных денег продажами
    /// — детерминированный эквивалент «аппетита к отрицательному балансу» для калибровки
    /// (<c>leverage</c>, Блок 7.3.2): реальный масштаб задаёт сам бот (доля этого потолка от
    /// <c>MinStartingLoanFraction</c> до 100%), эта величина — верхняя граница диапазона. Игрок в
    /// UI этим не ограничен вовсе — просто строит, баланс уходит в минус, никакого специального
    /// «оформления» не требуется.
    /// </summary>
    public required decimal MaxInitialBuildBudget { get; init; }
}
