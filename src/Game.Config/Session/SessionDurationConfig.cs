namespace Game.Config.Session;

/// <summary>
/// Длительность сессии (SPEC §4). Пресетов длительности («короткая/средняя/полная») больше нет —
/// решение пользователя 2026-09-07: число ходов у нас одно, под него откалиброваны обе
/// производственные модели, а формат мероприятия подгоняется не длиной цепочки, а длиной хода —
/// то есть <see cref="PhaseTimingConfig"/> (90 ходов по минуте — полтора часа, по пять — семь с
/// половиной). Отдельного поля «ориентировочная длительность хода» здесь намеренно нет: длина хода
/// — это ровно сумма фаз, и второй, независимо редактируемый источник той же величины неизбежно
/// разъезжается с первым.
///
/// <para>
/// Жеребьёвка хода окончания при этом сохранена: точный ход выбирается из диапазона
/// [<see cref="MinTurns"/>, <see cref="MaxTurns"/>] на старте сессии, пишется в журнал и игрокам не
/// показывается — SPEC §«Окончание игры» называет это защитой от «предательства в финале»
/// (обесценивания репутации на последних ходах). Диапазон обязан лежать целиком выше горизонта
/// окупаемости цепочки: правило <c>docs/TODO.md</c> №22 требует, чтобы каждый уровень выходил в плюс
/// с запасом в 15 ходов до <see cref="MaxTurns"/>, и тогда даже самая ранняя из возможных концовок
/// застаёт команду уже окупившейся.
/// </para>
/// </summary>
public sealed record SessionDurationConfig
{
    /// <summary>Нижняя граница диапазона хода окончания игры.</summary>
    public required int MinTurns { get; init; }

    /// <summary>Верхняя граница диапазона хода окончания игры; по ней же планируют и боты, и все статические расчёты.</summary>
    public required int MaxTurns { get; init; }
}
