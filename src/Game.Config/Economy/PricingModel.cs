using System.Text.Json.Serialization;

namespace Game.Config.Economy;

/// <summary>
/// Модель ценообразования сделок с системой (продажа системе и аварийная закупка), выбирается на
/// сессию — <c>docs/external-economy.md</c> §8, реализация <c>docs/TODO.md</c> №27. Движок ветвится
/// по этому значению ровно в двух точках (<c>Game.Engine.MarketSaleCalculator</c> и
/// <c>Game.Engine.EmergencyPurchaseStep</c>), весь остальной код работает через общую цену и о
/// разрезе не знает.
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum PricingModel
{
    /// <summary>
    /// Цена сделки = себестоимость материала (<c>Game.Engine.MaterialCostCalculator</c>) ×
    /// фиксированная наценка. Упрощение, введённое 2026-08-21 специально ради отладки
    /// производственных цепочек, а не как механика реальной игры. **Сохраняется не как игровая
    /// опция, а как калибровочно-регрессионный режим:** делает воспроизводимыми уже снятые ботовые
    /// прогоны и даёт откат одной строкой на время перехода к <see cref="External"/>.
    /// </summary>
    CostPlus,

    /// <summary>
    /// Цена сделки задаётся внешней экономикой и от себестоимости во время партии не зависит вовсе:
    /// <c>BaseSellPrice(материал) × Индекс(ход) × Эластичность(давление предложения)</c>. Прибыль
    /// уровня становится <c>цена − себестоимость</c>, благодаря чему начинают вознаграждаться
    /// глубина передела и эффективность, а между командами появляется сравнительное преимущество
    /// (разбор трёх структурных дефектов cost-plus — <c>docs/economy-accounting-audit.md</c>).
    /// </summary>
    External,
}
