using Game.Domain;

namespace Game.Web;

/// <summary>Русские названия и пояснения ролей для интерфейса (SPEC §3) — единая точка, чтобы не расходились формулировки на разных страницах.</summary>
public static class RoleDisplay
{
    public static string Name(ParticipantRole role) => role switch
    {
        ParticipantRole.Manager => "Управляющий",
        ParticipantRole.Negotiator => "Переговорщик",
        ParticipantRole.Operator => "Оператор",
        ParticipantRole.Facilitator => "Ведущий",
        ParticipantRole.Administrator => "Администратор",
        _ => role.ToString(),
    };

    public static string Description(ParticipantRole role) => role switch
    {
        ParticipantRole.Manager => "Управляет командой целиком: фабрики, склад, R&D — и только он даёт финальное подтверждение сделок. Один на команду.",
        ParticipantRole.Negotiator => "Ведёт переговоры в зале и готовит черновики сделок на переговорной панели. Подтверждать сделки не может — это делает управляющий.",
        ParticipantRole.Operator => "Подтверждает сделки команд по коду, сверяя условия с бумажным бланком. Не привязан к команде.",
        ParticipantRole.Facilitator => "Управляет игрой целиком: пауза/продление фаз, вмешательство в экономику, полный обзор всех команд.",
        ParticipantRole.Administrator => "Настраивает сессию до игры: конфиг, команды, участники — и следит за её ходом.",
        _ => string.Empty,
    };

    public static IReadOnlyList<string> Tips(ParticipantRole role) => role switch
    {
        ParticipantRole.Manager =>
        [
            "Построить фабрику, нанять/уволить рабочих, вложиться в R&D",
            "Продать материал системе или заключить контракт с другой командой",
            "Подтвердить черновик сделки, который подготовил переговорщик",
            "Добавить участников своей команды — ниже на этой странице",
        ],
        ParticipantRole.Negotiator =>
        [
            "Смотреть состояние команды и доску потребностей",
            "Договариваться с другими командами в зале и готовить черновик сделки",
            "Подтверждать сделки не может — только управляющий",
        ],
        ParticipantRole.Operator =>
        [
            "Принимать код сделки от участников и сверять его с бумажным бланком",
            "Подтверждать сделку одним действием или отклонять с причиной",
        ],
        ParticipantRole.Facilitator =>
        [
            "Стартовать/ставить на паузу/продлевать фазы хода",
            "Видеть все команды целиком и вмешиваться в экономику вручную",
            "Публиковать новости, выдавать гранты, включать/выключать аварийную закупку",
        ],
        ParticipantRole.Administrator =>
        [
            "Настраивать конфиг, пресет длительности, команды и участников до старта",
            "Следить за чек-листом готовности и запускать сессию",
            "Печатать памятки команд и бланки сделок",
        ],
        _ => [],
    };
}
