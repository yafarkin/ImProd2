namespace Game.Engine;

/// <summary>
/// Базовый тип для любого события, способного изменить <typeparamref name="TState"/> (AGENTS §2,
/// правило 5: любое изменение состояния — через журнал). Чистая инфраструктура event sourcing —
/// конкретные игровые события (производство, контракты, финансы, ...) унаследуют этот тип, когда
/// появятся сами эти предметные области; пока их нет, и ни один конкретный
/// <see cref="Change{TState}"/> в этом проекте не определён.
/// </summary>
public abstract record Change<TState>
{
    /// <summary>
    /// Идентификатор события. Передаётся вызывающим кодом, а не генерируется здесь — тогда
    /// воспроизведение сохранённого журнала даёт те же самые id, а не новые при каждом прогоне.
    /// </summary>
    public required Ulid Id { get; init; }

    /// <summary>Изменяет <paramref name="state"/> на месте, отражая то, что это событие произошло.</summary>
    public abstract void Apply(TState state);
}
