namespace Game.Engine;

/// <summary>
/// Фаза хода (SPEC §4): расчёт+завершение → решения → расчёт+завершение следующего хода. Решения
/// команд допустимы только в фазе <see cref="Decision"/>. Раньше расчёт и завершение были двумя
/// отдельными фазами (Calculation/Closing) — но сам расчёт (<see cref="GameSession.RunTick"/>)
/// атомарен и мгновенен (миллисекунды), исполняется одним действием сразу при входе в
/// <see cref="Settlement"/>, а не «в течение» отведённого на фазу времени, — так что это были две
/// фазы простоя подряд с одинаковым поведением для игрока и разным названием. Объединены в одну.
/// </summary>
public enum TurnPhase
{
    /// <summary>
    /// Расчёт (сразу и атомарно при входе — <see cref="GameSession.RunTick"/>) плюс read-only буфер
    /// после него до начала решений следующего хода. Решения команд не принимаются.
    /// </summary>
    Settlement,

    /// <summary>Команды корректируют производство, ведут переговоры, заключают контракты.</summary>
    Decision
}
