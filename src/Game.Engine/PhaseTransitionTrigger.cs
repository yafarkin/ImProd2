namespace Game.Engine;

/// <summary>
/// Источник перехода к следующей фазе хода (SPEC §4: гибрид — таймер по умолчанию, ведущий может
/// ускорить). Хранится в <see cref="PhaseAdvanced"/>, чтобы при разборе журнала можно было отличить
/// автоматический переход по таймеру от ручного вмешательства ведущего, а не выводить это из
/// соседних записей (AGENTS-память: причина и источник решения — часть самого события).
/// </summary>
public enum PhaseTransitionTrigger
{
    /// <summary>Фаза завершилась по истечении отведённого времени.</summary>
    Timer,

    /// <summary>Ведущий принудительно завершил фазу раньше срока («ускорить»).</summary>
    Facilitator
}
