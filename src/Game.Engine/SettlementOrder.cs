using Game.Domain;

namespace Game.Engine;

/// <summary>
/// Порядок, в котором расчёт хода (<see cref="GameSession.RunTick"/>) обходит команды: продажа системе,
/// аварийная закупка, производство внутри уровня цепочки.
///
/// <para>
/// <b>Зачем он меняется от хода к ходу.</b> Цена сбыта падает по мере того, как зал продаёт материал
/// (эластичность по давлению предложения, <c>docs/external-economy.md</c> §2.2), а давление копится
/// уже внутри хода — команда, которую расчёт обошёл раньше, продаёт до того, как её же объём и объём
/// соседа по сектору сбили цену. При постоянном порядке «по возрастанию <c>Team.Id</c>» это
/// преимущество доставалось одной и той же команде всю партию, а <c>Team.Id</c> — Ulid по времени
/// создания, то есть выигрывал тот, кто раньше зарегистрировался. Замер на <c>main-3-sectors</c>
/// (2 одинаковых бота на сектор, <c>External</c>, 2026-09-24): ротация расчёта сняла 3,4–4,7 тыс. из
/// преимущества ранней команды сектора (при счёте команды 20–50 тыс.); остальное давало сведение
/// равных заявок в стакане ботов (<c>OrderBook</c>), исправлено там же.
/// </para>
///
/// <para>
/// <b>Правило.</b> Базовый список — команды по возрастанию <c>Team.Id</c>. На ходе <c>t</c> он
/// циклически сдвигается на <c>(t − 1) mod N</c>, а каждые <c>N</c> ходов направление обхода
/// меняется на обратное. За цикл из <c>2N</c> ходов каждая команда ровно дважды стоит на каждом
/// месте, а каждая пара команд ровно половину ходов идёт в одном порядке и половину в другом. Один
/// только сдвиг этого не даёт: соседние по списку команды при сдвиге идут в одном порядке в
/// <c>N − 1</c> ходах из <c>N</c>. Правило детерминировано (зависит только от номера хода и набора
/// команд — AGENTS правило 6) и не требует случайности.
/// </para>
/// </summary>
public static class SettlementOrder
{
    public static IReadOnlyList<Team> ForTurn(IEnumerable<Team> teams, int turn)
    {
        ArgumentNullException.ThrowIfNull(teams);

        var ordered = teams.OrderBy(team => team.Id).ToList();
        var count = ordered.Count;
        if (count <= 1)
        {
            return ordered;
        }

        var step = Math.Max(turn - 1, 0);
        var shift = step % count;
        var reversed = (step / count) % 2 == 1;

        var result = new List<Team>(count);
        for (var i = 0; i < count; i++)
        {
            result.Add(ordered[(shift + i) % count]);
        }

        if (reversed)
        {
            result.Reverse();
        }

        return result;
    }
}
